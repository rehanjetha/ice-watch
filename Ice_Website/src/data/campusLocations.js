export const KEELE_CENTER = [43.7735, -79.5019];
export const KEELE_ZOOM = 15;

export const CAMPUS_LOCATIONS_BY_LABEL = YORK_KEELE_LOCATIONS.reduce((acc, location) => {
  acc[location.label] = location;
  return acc;
}, {});

export const LOCATION_RADII = YORK_KEELE_LOCATIONS.reduce((acc, location) => {
  acc[location.label] = location.defaultRadius ?? DEFAULT_SENSOR_RADIUS;
  return acc;
}, {});

export function getCampusLocation(label) {
  return CAMPUS_LOCATIONS_BY_LABEL[label] || null;
}

export function getDefaultRadiusForLocation(label) {
  return LOCATION_RADII[label] || DEFAULT_SENSOR_RADIUS;
}

export function searchCampusLocations(query) {
  const normalizedQuery = query.trim().toLowerCase();
  if (!normalizedQuery) {
    return YORK_KEELE_LOCATIONS;
  }

  return YORK_KEELE_LOCATIONS.filter((location) => {
    const haystack = [
      location.label,
      location.code,
      ...(location.aliases || []),
      location.category,
    ]
      .filter(Boolean)
      .join(" ")
      .toLowerCase();

    return haystack.includes(normalizedQuery);
  });
}
